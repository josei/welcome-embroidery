// Regenerates fonts/neon_blinking/glyphs.js from glyphs.json. The editor imports the .js form because Safari (and older Firefox) cannot load
// JSON modules (`import x from './a.json' with {type:'json'}`) inside module workers, which made the stitch worker fail to start there.
import fs from 'node:fs';
const dir=new URL('../fonts/neon_blinking/',import.meta.url),json=fs.readFileSync(new URL('glyphs.json',dir),'utf8');
fs.writeFileSync(new URL('glyphs.js',dir),`// Generated by scripts/make-neon-module.mjs from glyphs.json - do not edit.\nexport default ${JSON.stringify(JSON.parse(json))};\n`);
console.log('wrote fonts/neon_blinking/glyphs.js');
