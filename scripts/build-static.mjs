import fs from 'node:fs/promises';
import {build} from 'vite';
await fs.rm('dist',{recursive:true,force:true});
await build({configFile:'vite.config.js',logLevel:'warn'});
let html=await fs.readFile('dist/index.html','utf8');
const link=html.match(/<link rel="stylesheet"[^>]*href="\.\/(assets\/[^"]+\.css)"[^>]*>/);
if(!link)throw Error('Expected bundled stylesheet link was not found.');
const css=await fs.readFile(`dist/${link[1]}`,'utf8');
html=html.replace(link[0],`<meta name="welcome-static" content="true"><style>\n${css}\n</style>`);
await fs.writeFile('dist/index.html',html);
await fs.rm(`dist/${link[1]}`);
await fs.cp('fonts','dist/fonts',{recursive:true});
for(const file of ['LICENSE','THIRD_PARTY_NOTICES.md','LICENSE-THIRD-PARTY-pystitch.txt','LICENSE-THIRD-PARTY-polygon-clipping.txt'])await fs.copyFile(file,`dist/${file}`);
console.log('Built self-contained static asset tree in dist/ with a bundled editor, embedded CSS, relative assets and fonts, and license notices.');
